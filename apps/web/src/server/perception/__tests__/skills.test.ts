// @vitest-environment node
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it, vi } from 'vitest';
vi.mock('server-only', () => ({}));
import { KIT_ARCHETYPES } from '@/lib/object-kit';
import { RECIPE_MATERIALS } from '@/lib/object-shape';
import { CARD_TEXT } from '../skills/cards.generated';
import { extractCards } from '../skills/extract';
import { archetypeCard, imageCard, skillFor, type SkillCall } from '../skills';

const DOC = join(process.cwd(), '../../docs/vision-to-3d-muse-skills.md');
const CALLS: SkillCall[] = ['kit', 'free', 'critic', 'stages', 'views', 'final', 'judge'];
const words = (s: string) => s.split(/\s+/).filter(Boolean).length;

/** `make skills-gen` (SKILLS_GEN=1): rewrites `cards.generated.ts` from the doc. */
describe.runIf(process.env.SKILLS_GEN)('make skills-gen', () => {
  it('writes cards.generated.ts from the doc', () => {
    const cards = extractCards(readFileSync(DOC, 'utf8'));
    writeFileSync(
      join(process.cwd(), 'src/server/perception/skills/cards.generated.ts'),
      `// Generated by \`make skills-gen\` from docs/vision-to-3d-muse-skills.md. Do not edit.\nexport const CARD_TEXT: Readonly<Record<string, string>> = ${JSON.stringify(cards, null, 2)};\n`
    );
    console.info(`${Object.keys(cards).length} cards written`);
  });
});

describe('skill cards (PQ-T11)', () => {
  it('the module carries the same text as the doc (run make skills-gen when this fails)', () => {
    expect(CARD_TEXT).toEqual(extractCards(readFileSync(DOC, 'utf8')));
  });

  it('extracts the first block of each section and one card per archetype id', () => {
    const md = [
      '## 2. BASE card',
      '```',
      'base text',
      '```',
      '```',
      'an example, not the card',
      '```',
      '### 5.8 `lamp_post` and `pole`',
      '```',
      'POLES',
      '```',
      '### 5.9 not a card',
      'no block',
    ].join('\n');
    expect(extractCards(md)).toEqual({
      base: 'base text',
      'archetype:lamp_post': 'POLES',
      'archetype:pole': 'POLES',
    });
  });

  it('every archetype resolves to a card, `other` to none', () => {
    for (const a of KIT_ARCHETYPES) {
      if (a === 'other') expect(archetypeCard(a)).toBeNull();
      else expect(archetypeCard(a), a).toMatch(/^[A-Z][A-Z /]+\b/);
    }
    expect(skillFor('kit', 'other').cards).toEqual(['base', 'look', 'kit']);
    expect(skillFor('kit', 'vehicle').cards).toEqual(['base', 'look', 'kit', 'archetype:vehicle']);
    // No family for the free-parts call, none for the blind judge.
    expect(skillFor('free', 'vehicle').cards).toEqual(['base', 'look', 'free']);
    expect(skillFor('judge', 'vehicle').cards).toEqual(['base', 'judge']);
  });

  it('every composed prompt is at most 1 200 words, and the version follows the text', () => {
    for (const call of CALLS)
      for (const a of KIT_ARCHETYPES) {
        const s = skillFor(call, a);
        expect(words(s.text), `${call}/${a}`).toBeLessThanOrEqual(1200);
        expect(s.version).toMatch(/^[0-9a-f]{8}$/);
      }
    expect(skillFor('kit', 'vehicle').version).not.toBe(skillFor('kit', 'house').version);
    expect(skillFor('kit', 'house').version).toBe(skillFor('kit', 'house').version);
  });

  it('no card but Base (which forbids them) speaks of watts, kW or metres', () => {
    for (const [name, text] of Object.entries(CARD_TEXT)) {
      if (name === 'base') continue;
      expect(text, name).not.toMatch(/\b(watts?|kwh?|metres?|meters?)\b/i);
    }
  });

  it('every material a card names is a recipe material (`painted` waits for PQ-T39)', () => {
    const allowed = new Set<string>([...RECIPE_MATERIALS, 'painted']);
    const listed = CARD_TEXT.base!.match(/Materials: ([^\n]+(?:\n {2}[^\n]+)*)/)![1]!;
    // « stone, brick, …, water. Nothing else. »: the list stops at the first full stop.
    for (const m of listed.replace(/\s+/g, ' ').split('.')[0]!.split(/,\s*/))
      expect(allowed.has(m.trim()), m).toBe(true);
    // The cue lines of the kit card: « name: … · name: … ».
    const cues = CARD_TEXT.kit!.split('Material cues')[1]!;
    for (const m of cues.matchAll(/(?:^|·)\s*-?\s*([a-z]+):/gm)) {
      expect(allowed.has(m[1]!), m[1]).toBe(true);
    }
  });

  it('every SAM word list holds 1 to 3 plain words per item', () => {
    let lists = 0;
    for (const [name, text] of Object.entries(CARD_TEXT)) {
      const m = text.match(/^SAM words: (.+)\.$/m);
      if (!name.startsWith('archetype:')) continue;
      // A flat family (water) has no parts to ask for.
      if (!m) {
        expect(name).toBe('archetype:water');
        continue;
      }
      lists++;
      for (const item of m![1]!.split(/,\s*/)) {
        const n = words(item);
        expect(n >= 1 && n <= 3, `${name}: "${item}"`).toBe(true);
      }
    }
    expect(lists).toBeGreaterThanOrEqual(KIT_ARCHETYPES.length - 2);
  });

  it('serves the image cards and fails loudly on a missing one', () => {
    expect(imageCard('side')).not.toBe('');
    expect(imageCard('cleanFront')).not.toBe('');
  });
});
